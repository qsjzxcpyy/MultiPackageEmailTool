import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { createApp } from '../../server.mjs';
import { MailJobs, writeMailSnapshot } from '../../mail_jobs.mjs';
import { filterMailRecords, visibleMailRecords } from '../../web/mail.js';

test('mail history API requires deliberate same-origin send; fake worker only; survives restart', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(),'mail-api-offline-'));
  t.after(() => fs.rm(root,{recursive:true,force:true}));
  const dataDir = path.join(root,'history');
  const workbook = path.join(root,'fake.xlsx');
  await fs.writeFile(workbook,'fake worker placeholder');
  const batch = await new MailJobs({dataDir}).create([{订单号:'SYNTHETIC-111',来源:'ZE',收件邮箱:'buyer@example.com',发件邮箱:'demo@qq.com',邮件内容:'Synthetic body'}],workbook);
  let calls = 0;
  let finish;
  const server = createApp({rootDir:root,mailDataDir:dataDir,launchWorker:async input => {
    calls++;
    await new Promise(resolve => {finish=resolve;});
    await writeMailSnapshot(input.progressPath,{phase:'completed',records:[{status:'sent',attempts:1,detail:'Fake accepted'}]});
  }});
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  t.after(() => server.shutdown());
  const base = `http://127.0.0.1:${server.address().port}`;
  assert.equal((await (await fetch(`${base}/api/mail/batches`)).json()).batches.length,1);
  assert.equal(calls,0);
  const route = `${base}/api/mail/batches/${batch.id}/send`;
  assert.equal((await fetch(route,{method:'POST',body:'fake'})).status,403);
  const {token} = await (await fetch(`${base}/api/mail/session`)).json();
  assert.equal((await fetch(route,{method:'POST',headers:{'X-Mail-Token':token,Origin:'https://external.invalid'},body:'fake'})).status,403);
  assert.equal(calls,0);
  const response = await fetch(route,{method:'POST',headers:{'X-Mail-Token':token},body:'demo@qq.com----fictional'});
  assert.equal(response.status,202);
  assert.equal(calls,1);
  assert.equal((await fetch(route,{method:'POST',headers:{'X-Mail-Token':token},body:'fake'})).status,409);
  finish();
  await server.shutdown();
  const restored = await new MailJobs({dataDir}).get(batch.id);
  assert.equal(restored.counts.sent,1);
  assert.equal(restored.records[0].邮件内容,'Synthetic body');
});
test('order search, unsuccessful filter and store filter compose', () => {
  const rows = [{订单号:'TEST-111',来源:'ZE',status:'sent'}, {订单号:'TEST-222',来源:'ZE',status:'failed',detail:'550'}, {订单号:'TEST-333',来源:'XO',status:'uncertain'}];
  assert.deepEqual(filterMailRecords(rows,'222','unsuccessful','ZE'),[rows[1]]);
  assert.deepEqual(filterMailRecords(rows,'','unsuccessful'),rows.slice(1));
  assert.deepEqual(filterMailRecords(rows,'550'),[rows[1]]);
});
test('delivery feed reveals only started orders; untouched pending orders stay out of feed', () => {
  const records = [{status:'pending',attempts:0},{status:'sending',attempts:1},{status:'sent'}, {status:'failed'}, {status:'uncertain'}];
  assert.deepEqual(visibleMailRecords(records),records.slice(1));
  assert.deepEqual(visibleMailRecords([{status:'pending',attempts:2}]),[]);
});
test('default authorization and saved replacement allow sending without another file selection', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(),'mail-default-api-'));
  t.after(() => fs.rm(root,{recursive:true,force:true}));
  const defaultPath = path.join(root,'existing.txt');
  await fs.writeFile(defaultPath,'demo@qq.com----fictional-default');
  const dataDir = path.join(root,'history');
  const workbook = path.join(root,'fake.xlsx');
  await fs.writeFile(workbook,'fake worker placeholder');
  const batch = await new MailJobs({dataDir}).create([{订单号:'SYNTHETIC-DEFAULT',来源:'DEMO',收件邮箱:'buyer@example.com',发件邮箱:'demo@qq.com',邮件内容:'Synthetic'}],workbook);
  let calls=0;
  const server=createApp({rootDir:root,mailDataDir:dataDir,defaultCredentialFiles:[defaultPath],launchWorker:async input=>{
    calls++;
    assert.equal((await fs.readFile(input.authPath,'utf8')),'demo@qq.com----fictional-saved');
    await writeMailSnapshot(input.progressPath,{phase:'completed',records:[{status:'sent',attempts:1,detail:'Fake accepted'}]});
  }});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(()=>server.shutdown());
  const base=`http://127.0.0.1:${server.address().port}`;
  const credentialRoute=base+'/api/mail/credentials';
  const initial=await(await fetch(credentialRoute)).json();
  assert.equal(initial.ready,true);
  assert.equal(initial.filename,'existing.txt');
  assert.doesNotMatch(JSON.stringify(initial),/fictional-default/);
  assert.equal(calls,0);
  assert.equal((await fetch(credentialRoute,{method:'POST',body:'fake'})).status,403);
  const {token}=await(await fetch(base+'/api/mail/session')).json();
  const headers={'X-Mail-Token':token,'X-Filename':'new.txt'};
  const saved=await(await fetch(credentialRoute,{method:'POST',headers,body:'demo@qq.com----fictional-saved'})).json();
  assert.equal(saved.ready,true);
  assert.equal(saved.filename,'new.txt');
  assert.equal((await fetch(credentialRoute,{method:'POST',headers,body:'malformed'})).status,400);
  assert.equal((await(await fetch(credentialRoute)).json()).filename,'new.txt');
  assert.equal(calls,0);
  assert.equal((await fetch(base+`/api/mail/batches/${batch.id}/send`,{method:'POST',headers:{'X-Mail-Token':token}})).status,202);
  await server.shutdown();
  assert.equal(calls,1);
  assert.equal((await new MailJobs({dataDir}).get(batch.id)).counts.sent,1);
  const savedFiles=await fs.readdir(path.join(root,'data','mail-settings'));
  assert.equal(savedFiles.filter(name=>name.endsWith('.txt')).length,1);
});
